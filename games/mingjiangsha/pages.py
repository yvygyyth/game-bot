"""名将杀 —— 游戏级公共页面。

**现在是空的**，而且这是有意的。

## 为什么空着

原来这里放着 `home`（首页），用**竞技卡**当识别特征。那是错的：竞技卡是
竞技功能的专属入口图（首页上还有「房间 / 战没 / 煮酒」三张并列的兄弟卡，
各属各自的功能），拿它定义"游戏级的首页"等于把首页的身份绑在竞技功能上 ——
别的功能为了认首页，得反过来引用竞技场的资源。

所以 `home` 跟着那张卡一起搬到了功能目录
（:mod:`games.mingjiangsha.jingji.pages`）。

## 代价，以及什么时候该填回来

代价是**每个功能都会声明自己的 `home`**（用自己那张卡认）。看着重复，
但它换来功能之间零依赖 —— 加新功能不会被迫引用另一个功能的图。

真要让首页回到游戏级，需要的是一件**所有功能共用、且只在首页出现**的特征。
实测过两个候选（同一台真机截图，在首页上都是 1.000）：

| 候选 | 非首页图上 | 能不能用 |
|---|---|---|
| 底部导航栏整条（公会/好友/伙伴/武将/任务） | 0.447 | 只在首页出现，是共用 UI |
| 四个模式卡整行（含卡之间的缝） | 0.451 | 但含"竞技"那张卡，仍有归属问题 |

**等到真有第二个功能、两边的 `home` 确实一模一样时**，再用底部导航栏把首页
提上来。现在就提是过早抽象：只有一个样本时，你没法知道"共用的那一块"到底
是哪一块。

## 这个文件为什么留着

"游戏级有公共页面"这件事本身要有个位置 —— 而不是让每个功能各自
``PageTree()``（那样以后加公共页就得改所有功能）。对应地，
:func:`games.mingjiangsha.game.new_tree` 返回的就是一棵空树。
"""

