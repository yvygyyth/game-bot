"""名将杀 —— 游戏级公共页面。

## 首页的识别特征用的是什么（以及为什么不是别的）

首页需要**一个稳定的特征**来回答"我现在在不在首页"。我量了四个候选，
结论和直觉相反，记在这里免得以后再踩：

| 候选 | 实拍图上 | 三种悬浮状态图上 | 能不能用 |
|---|---|---|---|
| 顶部资源条（金/钻/币） | 1.000，余量 0.379 | 1.000 / 1.000 / 1.000 | ❌ **框进了会变的数字** |
| 底部功能栏 | 1.000，余量 0.311 | 0.998 / 0.999 / 0.999 | ⚠️ 图标上会挂红点角标 |
| 左上角头像 | 1.000，余量 1.000 | **0.556 / 0.610 / 0.573** | ❌ 那个小人会动 |
| "一马当先"活动条 | 1.000 | 0.984 / 0.995 / 0.995 | ❌ 限时活动，会过期 |

（顶部资源条那条：它框进了金币数 2114、钻石 1.2万、元宝 23.3万 —— 数值一变模板就废。
底部功能栏那条：任务图标上的红点角标消失后就失配。）

最后选的是**竞技卡本身**：它只存在于首页，而且和"点它"用的是同一张图 ——
页面身份和动作目标永远不会自相矛盾。

它唯一的毛病是悬浮会变样，但那个**不需要两个模板** ——
实测正例最低 0.647、反例最高 0.439，中间空出 0.208，一个阈值就够
（详见 :mod:`games.mingjiangsha.shortcuts`）。

> 教训：**分数高不等于能用。** 顶部资源条分数最高，但它框进了会变的数字。
> 挑识别特征时要问三个问题：它会不会变？会不会被别的状态影响？它消失之后怎么办？
"""

