"""竞技场 · 累计局数 —— **跨运行**的记忆。

## 和 ``jingji.rounds`` 的区别（这两个极容易混）

====================  ============================  ==========================
                      ``jingji.rounds``（运行参数）  ``jingji.runs``（状态仓库）
====================  ============================  ==========================
是什么                这次要刷几局                  历史上**总共**刷了几局
谁写                  用户（表单 / ``--param``）     脚本（每打完一局 +1）
关掉再开              还得重新填                     接着往上数
住哪                  ``ctx.param(...)``            ``ctx.store(RUNS)``
====================  ============================  ==========================

判断方法还是那句："**用户还没点开始时它就有值了吗？**" —— 有（用户填的）是参数；
得跑出来才有的，是仓库。

## 为什么这个值要跨运行

"今天刷了多少局""这个号一共刷了多少局"是**看进度**用的，不是这一次运行的输入。
放在黑板里的话，界面上点一下停止、再点开始，数字就归零了 —— 那正是这个仓库
要解决的问题。
"""

from __future__ import annotations

from gamebot.state.store import define_store

__all__ = ["RUNS"]

RUNS = define_store(
    "jingji.runs",
    title="累计局数",
    defaults={"done": 0, "last_finished_at": ""},
    help="跨运行累计；关掉界面再开也不会归零。和表单里的『刷几局』不是一回事",
)
"""仓库 id 的前缀 ``jingji.`` 是功能名。

同一游戏以后再加脚本（比如 ``qianli``）时它也会有自己的 ``runs``，前缀把两者
隔开；落盘文件是 ``data/stores/mingjiangsha/jingji.runs.json``。
"""
